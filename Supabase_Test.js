function runCode(app, puzzles) {
    // add your code here, e.g. console.log('Hello, World!');

    // --- НАСТРОЙКИ SUPABASE ---
    const SUPABASE_URL = 'https://ooubyyamxcthjigvepqx.supabase.co';
    const SUPABASE_ANON_KEY = 'sb_publishable_kXvx9gCbqncWWaEEhD2l6w_XON52bq-';
    const db = window.supabase.createClient(SUPABASE_URL, SUPABASE_ANON_KEY);

    let sawsState = {}; // Локальный кэш состояний { SM_Saw_01: { status, current_reason } }
    let selectedSawId = null;

    // Элементы DOM
    const modal = document.getElementById('saw-modal');
    const modalSawName = document.getElementById('modal-saw-name');
    const modalStatusBadge = document.getElementById('modal-status-badge');
    const stopControls = document.getElementById('stop-controls');
    const startControls = document.getElementById('start-controls');
    const currentReasonText = document.getElementById('current-reason-text');

    // 1. Функция, которую мы вызовем из Verge3D Puzzles при клике на 3D-объект
    // Регистрируем функцию в ExternalInterface для пазла call JS function
    app.ExternalInterface.openSawMenu = function(sawId) {
        selectedSawId = sawId;
        const saw = sawsState[sawId] || { status: 'running', current_reason: null };

        modalSawName.textContent = sawId;

        if (saw.status === 'running') {
            modalStatusBadge.textContent = 'Статус: В работе';
            modalStatusBadge.style.color = '#4ade80';
            stopControls.classList.remove('hidden');
            startControls.classList.add('hidden');
        } else {
            modalStatusBadge.textContent = 'Статус: Остановлен';
            modalStatusBadge.style.color = '#f87171';
            currentReasonText.textContent = `Причина: ${saw.current_reason}`;
            stopControls.classList.add('hidden');
            startControls.classList.remove('hidden');
        }

        modal.classList.remove('hidden');
    };

    document.getElementById('close-modal-btn').onclick = () => modal.classList.add('hidden');

    // 2. Обновление цвета станка в 3D-сцене (вызывает процедуру в Puzzles)
    function update3DSawVisual(sawId, status, reason) {
        if (puzzles && puzzles.procedures && puzzles.procedures['setSawColor']) {
            puzzles.procedures['setSawColor'](sawId, status, reason || '');
        }
    }

    // 3. Остановка станка (нажатие на причину)
    document.querySelectorAll('#stop-controls .action-btn').forEach(btn => {
        btn.onclick = async () => {
            if (!selectedSawId) return;
            const reason = btn.dataset.reason;
            const now = new Date().toISOString();

            // Обновляем текущий статус в таблице saws
            await db.from('saws').update({
                status: 'stopped',
                current_reason: reason,
                updated_at: now
            }).eq('id', selectedSawId);

            // Создаем новую запись в журнале простоев downtime_logs
            await db.from('downtime_logs').insert({
                saw_id: selectedSawId,
                reason: reason,
                stopped_at: now
            });

            modal.classList.add('hidden');
        };
    });

    // 4. Запуск станка
    document.getElementById('btn-start-saw').onclick = async () => {
        if (!selectedSawId) return;
        const now = new Date();
        const nowIso = now.toISOString();

        // Находим незакрытую запись простоя для этого станка
        const { data: openLogs } = await db
            .from('downtime_logs')
            .select('*')
            .eq('saw_id', selectedSawId)
            .is('started_at', null)
            .order('stopped_at', { ascending: false })
            .limit(1);

        if (openLogs && openLogs.length > 0) {
            const log = openLogs[0];
            const stoppedTime = new Date(log.stopped_at);
            const durationMinutes = Math.max(1, Math.round((now - stoppedTime) / 60000));

            await db.from('downtime_logs').update({
                started_at: nowIso,
                duration_minutes: durationMinutes
            }).eq('id', log.id);
        }

        // Переводим станок в статус running
        await db.from('saws').update({
            status: 'running',
            current_reason: null,
            updated_at: nowIso
        }).eq('id', selectedSawId);

        modal.classList.add('hidden');
        loadStats();
    };

    // 5. Подсчет статистики за текущие сутки
    async function loadStats() {
        const startOfDay = new Date();
        startOfDay.setHours(0, 0, 0, 0);

        const { data: logs } = await db
            .from('downtime_logs')
            .select('reason, duration_minutes')
            .gte('stopped_at', startOfDay.toISOString());

        if (!logs) return;

        let totalStops = logs.length;
        let totalMins = 0;
        const byReason = { 'Замена пил': 0, 'Ремонт': 0, 'Простой': 0 };

        logs.forEach(item => {
            const mins = item.duration_minutes || 0;
            totalMins += mins;
            if (byReason[item.reason] !== undefined) {
                byReason[item.reason] += mins;
            }
        });

        document.getElementById('stats-content').innerHTML = `
            <div>Остановок: <b>${totalStops}</b> (Всего: <b>${totalMins} мин</b>)</div>
            <div>Замена пил: ${byReason['Замена пил']} мин | Ремонт: ${byReason['Ремонт']} мин | Простой: ${byReason['Простой']} мин</div>
        `;
    }

    // 6. Начальная загрузка данных и подписка Realtime
    async function initMonitoring() {
        const { data: saws } = await db.from('saws').select('*');
        if (saws) {
            saws.forEach(saw => {
                sawsState[saw.id] = saw;
                update3DSawVisual(saw.id, saw.status, saw.current_reason);
            });
        }
        loadStats();

        // Слушаем изменения таблицы saws в реальном времени
        db.channel('saws-realtime')
            .on('postgres_changes', { event: 'UPDATE', schema: 'public', table: 'saws' }, payload => {
                const updatedSaw = payload.new;
                sawsState[updatedSaw.id] = updatedSaw;
                update3DSawVisual(updatedSaw.id, updatedSaw.status, updatedSaw.current_reason);
                loadStats();
            })
            .subscribe();
    }

    initMonitoring();

}


